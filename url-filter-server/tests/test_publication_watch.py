    def test_failed_activation_keeps_last_good_and_retries(self, rig):
        """Staged activation: a PIR-regen failure must NOT swap the
        Bloom/prefilter ahead of the PIR data. Last good keeps serving
        and the next poll retries the same generation."""
        root, ref, _, c = rig
        calls = {"n": 0}

        def flaky_hook(_dataset):
            calls["n"] += 1
            if calls["n"] == 1:
                raise RuntimeError("regen failed")

        w = PublicationWatcher(root, ref, on_swap=flaky_hook)
        publish(root, 2, ["staged.example"])
        assert w.check_once() == "failed"
        assert "regen failed" in w.status()["last_error"]
        # Nothing served from the half-activated generation.
        assert c.get("/v1/dataset/manifest").json()["version"] == 1
        # The NEXT poll retries the same generation and completes it.
        assert w.check_once() == "updated"
        assert calls["n"] == 2
        assert c.get("/v1/dataset/manifest").json()["version"] == 2

