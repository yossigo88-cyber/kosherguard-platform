"""B5 automatic chain: a control-plane publish (generation symlink
flip) must reach the served prefilter/shards by itself - no human
POST, no restart - with staged activation, last-good retention and
per-tenant isolation. The policy/categories fixtures are the control
plane's REAL published format (generated by
publication_ops.export_policy_documents), not hand-written."""

