"""PAC (Proxy Auto-Config) file generation from KosherGuard policies.

Apple's Global HTTP Proxy (supervised devices) points at a hosted PAC
URL. The PAC file routes blocked traffic to the filtering proxy and
everything else DIRECT.

Design decisions:
- The PAC is GENERATED from a published policy document, never
  hand-edited, so remote policy updates are republications.
- Blocking in a PAC is routing to the proxy; the proxy itself enforces.
  Blocked domains are matched by suffix (a blocklist entry covers its
  subdomains, matching engine semantics).
- Bypass rules: allowlist domains always go DIRECT, even under a
  blocked parent, matching the engine's allowlist-wins priority.
- Category rules CANNOT be expressed in a PAC directly (no dataset in
  the browser); domains in blocked categories are baked into the PAC's
  blocked list at generation time, and the proxy still enforces
  categories for routed traffic.
- The generated file is deterministic (sorted rules) so a republish of
  unchanged policy produces identical bytes.
"""

from __future__ import annotations

import json


class PACError(ValueError):
    pass


def _js_string(value: str) -> str:
    return json.dumps(value)


def _suffix_array(domains) -> str:
    return "[" + ", ".join(_js_string(d) for d in sorted(set(domains))) + "]"


def _expand_blocklist(policy: dict, categories: dict | None) -> list:
    """Blocklist plus domains whose categories the policy blocks."""
    allowlist = list(policy.get("allowlist", []))
    blocklist = list(policy.get("blocklist", []))
    blocked_categories = set(policy.get("category_rules", {}).get("block", []))
    allowed_categories = set(policy.get("category_rules", {}).get("allow", []))
    if categories and blocked_categories:
        for domain, cats in categories.get("domains", {}).items():
            catset = set(cats)
            if catset & blocked_categories and not catset & allowed_categories:
                if domain not in allowlist:
                    blocklist.append(domain)
    return blocklist


def generate_pac(policy: dict, categories: dict | None,
                 proxy_host: str, proxy_port: int) -> str:
    """Generate PAC file contents for one policy.

    policy: the engine-format document (default_policy, allowlist,
    blocklist, category_rules). categories: the category document
    (domains -> categories) used to bake category blocks into the PAC.
    proxy_host/proxy_port: the filtering proxy endpoint.
    """
    if not proxy_host or not isinstance(proxy_port, int) or \
            not (0 < proxy_port < 65536):
        raise PACError("a valid proxy host and port are required")
    default = policy.get("default_policy")
    if default not in ("allow", "block"):
        raise PACError("policy default_policy must be 'allow' or 'block'")

    allowlist = list(policy.get("allowlist", []))
    blocklist = _expand_blocklist(policy, categories)

    proxy = f"PROXY {proxy_host}:{proxy_port}"
    lines = [
        "// Generated by KosherGuard. Do not edit - republish instead.",
        f"var BYPASS = {_suffix_array(allowlist)};",
        f"var BLOCKED = {_suffix_array(blocklist)};",
        "",
        "function endsWithDomain(host, domain) {",
        "  return host === domain || dnsDomainIs(host, '.' + domain);",
        "}",
        "",
        "function inList(host, list) {",
        "  for (var i = 0; i < list.length; i++) {",
        "    if (endsWithDomain(host, list[i])) return true;",
        "  }",
        "  return false;",
        "}",
        "",
        "function FindProxyForURL(url, host) {",
        "  host = host.toLowerCase();",
        "  if (isPlainHostName(host)) return 'DIRECT';",
        "  if (inList(host, BYPASS)) return 'DIRECT';",
        "  if (inList(host, BLOCKED)) return " + _js_string(proxy) + ";",
    ]
    if default == "block":
        lines.append(f"  return {_js_string(proxy)};")
    else:
        lines.append("  return 'DIRECT';")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def evaluate_pac(policy: dict, categories: dict | None, host: str,
                 proxy_host: str = "proxy.local", proxy_port: int = 8080) -> str:
    """Reference evaluator mirroring the generated PAC's decisions,
    used by tests to check the generator without a JS runtime."""
    host = host.lower()
    if "." not in host:
        return "DIRECT"

    def ends(h, domain):
        return h == domain or h.endswith("." + domain)

    for d in policy.get("allowlist", []):
        if ends(host, d):
            return "DIRECT"
    for d in _expand_blocklist(policy, categories):
        if ends(host, d):
            return f"PROXY {proxy_host}:{proxy_port}"
    if policy.get("default_policy") == "block":
        return f"PROXY {proxy_host}:{proxy_port}"
    return "DIRECT"
